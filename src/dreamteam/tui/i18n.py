def t(lang: str | None, key: str, **kw: Any) -> str:
    """Text `key` in `lang` (falls back to English, then to the key), formatted with `kw`."""
    text = TEXTS.get(lang or "", {}).get(key)
    if text is None:
        text = TEXTS["en"].get(key, key)
    if kw:
        try:
            text = text.format(**kw)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def plural_index(lang: str | None, n: int) -> int:
    """Index of the plural form: ru one|few|many (1, 2-4, 5-20...), other languages one|other."""
    n = abs(int(n))
    if lang == "ru":
        if n % 10 == 1 and n % 100 != 11:
            return 0
        if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
            return 1
        return 2
    return 0 if n == 1 else 1


def tn(lang: str | None, key: str, n: int, **kw: Any) -> str:
    """Plural text `key` ("one|few|many") for the number `n` ({n} is filled in)."""
    raw = TEXTS.get(lang or "", {}).get(key)
    if raw is None:
        raw, lang = TEXTS["en"].get(key, key), "en"
    forms = raw.split("|")
    form = forms[min(plural_index(lang, n), len(forms) - 1)]
    try:
        return form.format(n=n, **kw)
    except (KeyError, IndexError, ValueError):
        return form
